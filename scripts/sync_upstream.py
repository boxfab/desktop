#!/usr/bin/env python3
"""Regenerate the upstream-derived parts of this repository from pinned E2B commits.

    python3 scripts/sync_upstream.py                         # clone both pinned commits
    python3 scripts/sync_upstream.py --monorepo <checkout> --desktop <checkout>

Sources (pins in UPSTREAM.md, checked against the checkouts):
  E2B monorepo  packages/desktop-python -> python/boxfab_desktop, python/tests, python/pytest.ini
                packages/desktop-js     -> js/src, js/tests
  e2b-dev/desktop  template/            -> template/ (template.py, build_*.py, files/)

Generated paths are never edited by hand: change a rule here and re-run. Every rule asserts how
often it matched, so when upstream moves code the sync fails instead of shipping an E2B default.
A final audit fails on any `e2b` import, E2B_* configuration variable or E2B link left behind.

First release: renames only (package and import names, BOXFAB_* variables, client class name,
docs). No behaviour change; see UPSTREAM.md for what is deliberately left unchanged.
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MONOREPO = "https://github.com/e2b-dev/E2B.git"
DESKTOP = "https://github.com/e2b-dev/desktop.git"

DOMAIN = "boxfab.io"

# Environment variables read by the desktop SDKs and their tests (the core SDK reads the rest).
ENV_VARS = ["API_KEY", "DOMAIN", "DEBUG", "API_URL", "SANDBOX_URL"]
ENV_RX = re.compile(r"\bE2B_(" + "|".join(ENV_VARS) + r")\b")

APACHE_NOTICE_PY = (
    "# Modified by ContextFab, Inc. for BoxFab: generated by scripts/sync_upstream.py\n"
    "# (SDK imports renamed to boxfab, see UPSTREAM.md). Licensed under Apache-2.0,\n"
    "# see LICENSE-E2B-DESKTOP.\n"
)

