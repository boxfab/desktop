PY_CLIENT_ALIAS = """

# Upstream name, kept so code written for the upstream package ports by changing only the import.
E2B = BoxFab
"""


def sync_python(mono: Path):
    up = mono / "packages/desktop-python"
    out = ROOT / "python"
    for d in ("boxfab_desktop", "tests"):
        shutil.rmtree(out / d, ignore_errors=True)
    shutil.copytree(up / "e2b_desktop", out / "boxfab_desktop", ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copytree(up / "tests", out / "tests", ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy2(up / "pytest.ini", out / "pytest.ini")
    shutil.copy2(up / "LICENSE", ROOT / "LICENSE-E2B")
    shutil.copy2(up / "CHANGELOG.md", out / "CHANGELOG-E2B.md")

    counts = {"imports": 0, "env": 0}
    for p in sorted([*out.joinpath("boxfab_desktop").rglob("*.py"), *out.joinpath("tests").rglob("*.py"), out / "pytest.ini"]):
        text = p.read_text()
        new = text
        new, n1 = re.subn(r"\be2b_desktop\b", "boxfab_desktop", new)
        new, n2 = re.subn(r"\bfrom e2b(?=[ .])", "from boxfab", new)
        new, n3 = re.subn(r"^(\s*)import e2b$", r"\1import boxfab", new, flags=re.M)
        new, n4 = ENV_RX.subn(r"BOXFAB_\1", new)
        counts["imports"] += n1 + n2 + n3
        counts["env"] += n4
        if new != text:
            p.write_text(new)
    expect = {"imports": 15, "env": 7}
    assert counts == expect, f"python renames: {counts}, expected {expect}"
    apply_exact(PY_EXACT)
    client = out / "boxfab_desktop/client.py"
    client.write_text(client.read_text().rstrip("\n") + "\n" + PY_CLIENT_ALIAS)
    print(f"  python: {counts}")


