README_START = "### 3. Create Desktop Sandbox\n"


def sync_readme(mono: Path, part: str, upstream_dir: str):
    text = (mono / "packages" / upstream_dir / "README.md").read_text()
    assert text.count(README_START) == 1, f"{upstream_dir}/README.md: section 3 heading changed"
    body = text[text.index(README_START):]
    for rx, repl, count in README_RULES[part] + README_COMMON:
        body, n = re.subn(rx, repl, body)
        assert n == count, f"{part} README {rx!r}: {n} matches, expected {count}"
    header = (ROOT / "overlay/readme" / f"header-{part}.md").read_text()
    (ROOT / part / "README.md").write_text(header + body)
    left = [l for l in body.splitlines() if re.search(r"e2b_desktop|@e2b/desktop|e2b\.dev|\bE2B\b|E2B_", l)]
    assert not left, f"{part} README: E2B references left: {left}"


