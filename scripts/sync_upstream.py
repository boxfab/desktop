def apply_exact(rules):
    for rel, old, new, expected in rules:
        p = ROOT / rel
        text = p.read_text()
        n = text.count(old)
        if n != expected:
            sys.exit(f"{rel}: expected {expected} x {old[:70]!r}, found {n}")
        p.write_text(text.replace(old, new))


def copy_overlay(part: str):
    base = ROOT / "overlay" / part
    for f in sorted(base.rglob("*")):
        if f.is_file():
            dst = ROOT / part / f.relative_to(base)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dst)


# What must not remain in generated code. The `e2b_` API-key prefix is protocol, not branding.
FORBIDDEN = [
    (re.compile(r"\b(from|import) e2b\b(?!_)"), "e2b import"),
    (re.compile(r"from 'e2b'"), "e2b import"),
    (re.compile(r"\be2b_desktop\b|@e2b/desktop"), "upstream package name"),
    (re.compile(r"\bE2B_(" + "|".join(ENV_VARS) + r")\b"), "E2B_* variable"),
    (re.compile(r"e2b\.dev|e2b\.app"), "E2B domain"),
]


def audit():
    problems = []
    paths = [*ROOT.joinpath("python/boxfab_desktop").rglob("*.py"), *ROOT.joinpath("js/src").rglob("*.ts"),
             *[ROOT / "template" / n for n in TEMPLATE_FILES]]
    for p in paths:
        for i, line in enumerate(p.read_text().splitlines(), 1):
            for rx, what in FORBIDDEN:
                if rx.search(line):
                    problems.append(f"{p.relative_to(ROOT)}:{i}: {what}: {line.strip()}")
    if problems:
        sys.exit("audit failed:\n  " + "\n  ".join(problems))


def pin(name: str) -> str:
    m = re.search(rf"^- {name} commit: `([0-9a-f]{{40}})`", (ROOT / "UPSTREAM.md").read_text(), re.M)
    if not m:
        sys.exit(f"UPSTREAM.md has no '- {name} commit: `<sha>`' line")
    return m.group(1)


def checkout(url: str, ref: str, given: Path | None, tmp: Path, name: str) -> Path:
    if given is None:
        given = tmp / name
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", url, str(given)], check=True)
        subprocess.run(["git", "-C", str(given), "checkout", "-q", ref], check=True)
    head = subprocess.run(["git", "-C", str(given), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    if head != ref:
        sys.exit(f"{given} is at {head}, UPSTREAM.md pins {ref}")
    return given


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--monorepo", type=Path, help="E2B monorepo checkout at the pinned commit")
    ap.add_argument("--desktop", type=Path, help="e2b-dev/desktop checkout at the pinned commit")
    a = ap.parse_args()
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        mono = checkout(MONOREPO, pin("Monorepo"), a.monorepo, Path(tmp), "E2B")
        desk = checkout(DESKTOP, pin("Desktop repo"), a.desktop, Path(tmp), "desktop")
        sync_python(mono)
        sync_js(mono)
        sync_template(desk)
        sync_readme(mono, "python", "desktop-python")
        sync_readme(mono, "js", "desktop-js")
    # Each package ships both license texts (packaging cannot reach files above its root).
    for part in ("python", "js"):
        for name in ("LICENSE", "LICENSE-E2B"):
            shutil.copy2(ROOT / name, ROOT / part / name)
    audit()
    print("sync OK")


if __name__ == "__main__":
    main()
