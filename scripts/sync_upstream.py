def sync_js(mono: Path):
    up = mono / "packages/desktop-js"
    out = ROOT / "js"
    for d in ("src", "tests"):
        shutil.rmtree(out / d, ignore_errors=True)
        shutil.copytree(up / d, out / d)
    shutil.copy2(up / "CHANGELOG.md", out / "CHANGELOG-E2B.md")
    for rel in JS_DELETE:
        p = out / rel
        assert p.is_dir(), f"JS_DELETE: {rel} not found upstream"
        shutil.rmtree(p)
    copy_overlay("js")

    counts = {"imports": 0, "env": 0, "links": 0}
    for p in sorted([*out.joinpath("src").rglob("*.ts"), *out.joinpath("tests").rglob("*.ts")]):
        if "boxfab-env.setup.ts" in p.name:
            continue
        text = p.read_text()
        new, n1 = re.subn(r"from 'e2b'", "from 'boxfab'", text)
        new, n2 = ENV_RX.subn(r"BOXFAB_\1", new)
        new, n3 = re.subn(r"\{@link E2B(\.\w+)?\}", r"{@link BoxFab\1}", new)
        counts["imports"] += n1
        counts["env"] += n2
        counts["links"] += n3
        if new != text:
            p.write_text(new)
    expect = {"imports": 4, "env": 6, "links": 4}
    assert counts == expect, f"js renames: {counts}, expected {expect}"
    apply_exact(JS_EXACT)
    # index.ts re-exports the core SDK first; the explicit exports above shadow its BoxFab/E2B.
    idx = out / "src/index.ts"
    t = idx.read_text()
    assert t.count("export * from 'boxfab'") == 1, "js/src/index.ts: core re-export changed upstream"
    print(f"  js: {counts}")


