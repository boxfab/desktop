#!/usr/bin/env python3
"""Regenerate the upstream-derived parts of this repository from the pinned e2b-dev/desktop commit.

    python3 scripts/sync_upstream.py                    # clone the pinned commit
    python3 scripts/sync_upstream.py --desktop <checkout>

Source (pins in UPSTREAM.md, checked against the checkout): e2b-dev/desktop
    template/                      -> template/ (template.py, build_*.py, files/)
    README.md                      -> README.md (our introduction, then upstream's API sections)
    examples/streaming-apps-*/     -> examples/streaming-apps-*/README.md

The SDKs are generated in boxfab/python-sdk (desktop/) and boxfab/js-sdk (desktop/).

Generated paths are never edited by hand: change a rule here and re-run. Every rule asserts how
often it matched, so when upstream moves text the sync fails instead of shipping an E2B default.
A final audit fails on any `e2b` import, upstream package name or E2B link left behind.
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESKTOP = "https://github.com/e2b-dev/desktop.git"

# Files derived from the Apache-2.0 upstream carry this notice (Apache-2.0 section 4(b)).
NOTICE_PY = (
    "# Modified by ContextFab, Inc. for BoxFab: generated by scripts/sync_upstream.py\n"
    "# (SDK imports renamed to boxfab, see UPSTREAM.md). Licensed under Apache-2.0,\n"
    "# see LICENSE.\n"
)
NOTICE_MD = (
    "<!-- Modified by ContextFab, Inc. for BoxFab: generated by scripts/sync_upstream.py from\n"
    "     e2b-dev/desktop (Apache-2.0, see LICENSE and UPSTREAM.md). Do not edit by hand. -->\n"
)

# --------------------------------------------------------------------------------------------
# Template (Apache-2.0)

TEMPLATE_FILES = ["template.py", "build_prod.py", "build_dev.py", "build_docker.py"]

# template.py rewrites: noVNC pinned to a commit (upstream follows the e2b-desktop branch); the
# noVNC page's title and icons, and the sandbox hostname, changed to BoxFab. BoxFab's runtime
# names every sandbox e2b.local; until the platform-wide patch lands, the template sets it.
TEMPLATE_EXACT = [
    ('''    .git_clone(
        "https://github.com/e2b-dev/noVNC.git", "/opt/noVNC", branch="e2b-desktop"
    )
''', '''    .run_cmd(
        "git clone -q -b e2b-desktop https://github.com/e2b-dev/noVNC.git /opt/noVNC"
        " && git -C /opt/noVNC checkout -q {NOVNC}"
    )
''', 1),
    ('''            CopyItem(src="firefox.cfg", dest="/usr/lib/firefox-esr/firefox.cfg"),
        ]
    )
)
''', r'''            CopyItem(src="firefox.cfg", dest="/usr/lib/firefox-esr/firefox.cfg"),
        ]
    )
    # BoxFab: noVNC page title and icons, and the sandbox hostname (UPSTREAM.md, "Rewrites")
    .copy("novnc-icons", "/opt/noVNC/app/images/icons/boxfab")
    .run_cmd(
        [
            "test -f /opt/noVNC/app/images/icons/boxfab/favicon.svg",
            "rm -rf /opt/noVNC/app/images/icons/e2b",
            "sed -i -e 's#<title>E2B VNC</title>#<title>BoxFab Desktop</title>#'"
            " -e 's#app/images/icons/e2b/#app/images/icons/boxfab/#g' /opt/noVNC/vnc.html",
            "! grep -qi e2b /opt/noVNC/vnc.html",
            "hostname boxfab.local",
            "echo boxfab.local > /etc/hostname",
            "sed -i 's/^127\\.0\\.1\\.1\\s.*/127.0.1.1\\tboxfab.local/' /etc/hosts",
        ]
    )
)
''', 1),
]


def sync_template(desk: Path):
    up = desk / "template"
    out = ROOT / "template"
    shutil.rmtree(out / "files", ignore_errors=True)
    shutil.copytree(up / "files", out / "files")
    n = 0
    for name in TEMPLATE_FILES:
        text = (up / name).read_text()
        new, k = re.subn(r"^from e2b import\b", "from boxfab import", text, flags=re.M)
        n += k
        (out / name).write_text(NOTICE_PY + new)
    assert n == 4, f"template imports: {n}, expected 4"
    copy_overlay("template")  # our wallpaper.png replaces upstream's; adds files/novnc-icons/
    apply_exact([("template/template.py", old, new.replace("{NOVNC}", pin("noVNC")), k)
                 for old, new, k in TEMPLATE_EXACT])
    # Upstream's template keeps the alias `desktop` (prod) / `desktop-dev` (dev) and the resources.
    for name, needle in [("build_prod.py", 'alias="desktop"'), ("build_dev.py", 'alias="desktop-dev"'),
                         ("build_prod.py", "cpu_count=8"), ("build_prod.py", "memory_mb=8192")]:
        assert needle in (out / name).read_text(), f"template/{name}: {needle} not found"
    print(f"  template: {n} imports, {len(list((out / 'files').iterdir()))} files")


# --------------------------------------------------------------------------------------------
# README: our introduction (overlay/readme/header.md) replaces upstream's up to
# "### 3. Create Desktop Sandbox"; the API sections after it are upstream's, renamed; our
# paragraphs go into "Under the hood"; overlay/readme/footer.md (License) closes it.

README_START = "### 3. Create Desktop Sandbox\n"
README_RULES = [
    (r"\be2b_desktop\b", "boxfab_desktop", 12),
    (r"'@e2b/desktop'", "'@boxfab/desktop'", 12),
    (r"(Check out the sandbox template's code \[here\]\(\./template/\)\.\n)",
     r"\1\nPLACEHOLDER_UNDER_THE_HOOD\n", 1),
]


def sync_readme(desk: Path):
    text = (desk / "README.md").read_text()
    assert text.count(README_START) == 1, "README.md: section 3 heading changed upstream"
    body = text[text.index(README_START):]
    for rx, repl, count in README_RULES:
        body, n = re.subn(rx, repl, body)
        assert n == count, f"README {rx!r}: {n} matches, expected {count}"
    body = body.replace("PLACEHOLDER_UNDER_THE_HOOD\n", (ROOT / "overlay/readme/under-the-hood.md").read_text())
    header = (ROOT / "overlay/readme/header.md").read_text()
    footer = (ROOT / "overlay/readme/footer.md").read_text()
    (ROOT / "README.md").write_text(NOTICE_MD + header + body.rstrip("\n") + "\n" + footer)
    print("  README: header + upstream sections + footer")


# --------------------------------------------------------------------------------------------
# Examples: upstream's streaming-apps READMEs, renamed. The basic examples (pywebview/Electron
# windows) are not included; examples/computer-use-claude-python is this repository's own.

EXAMPLES = {
    "streaming-apps-python": [
        ("pip install e2b-desktop", "pip install boxfab-desktop", 1),
        ("from e2b_desktop import Sandbox", "from boxfab_desktop import Sandbox", 1),
    ],
    "streaming-apps-javascript": [
        ("npm install @e2b/desktop", "npm install @boxfab/desktop", 1),
        ("from '@e2b/desktop'", "from '@boxfab/desktop'", 1),
    ],
}
EXAMPLES_COMMON = [
    ("Streaming applications is a feature of the E2B Desktop Sandbox.",
     "Streaming applications is a feature of BoxFab Desktop.", 1),
    # upstream's screenshots show E2B's domain in the address bar
    ("| Streaming Chrome Window                                 | Streaming VS Code Window                                 |\n"
     "| ------------------------------------------------------- | -------------------------------------------------------- |\n"
     "| ![Chrome streaming window](../readme-assets/chrome.png) | ![VS Code streaming window](../readme-assets/vscode.png) |\n\n",
     "", 1),
    ("### 1. Get E2B API key\n\nSign up at [E2B](https://e2b.dev) and get your API key.\n"
     "Set environment variable `E2B_API_KEY` with your API key.\n",
     "### 1. Get a BoxFab API key\n\nGet a key from the [BoxFab dashboard](https://dashboard.boxfab.io) "
     "and set it as `BOXFAB_API_KEY`.\n", 1),
]


def sync_examples(desk: Path):
    for name, rules in EXAMPLES.items():
        text = (desk / "examples" / name / "README.md").read_text()
        for old, new, count in rules + EXAMPLES_COMMON:
            n = text.count(old)
            assert n == count, f"examples/{name}: {old[:60]!r} found {n}x, expected {count}"
            text = text.replace(old, new)
        out = ROOT / "examples" / name
        out.mkdir(parents=True, exist_ok=True)
        (out / "README.md").write_text(NOTICE_MD + text)
    print(f"  examples: {', '.join(EXAMPLES)}")


# --------------------------------------------------------------------------------------------


def apply_exact(rules):
    for rel, old, new, expected in rules:
        p = ROOT / rel
        text = p.read_text()
        n = text.count(old)
        if n != expected:
            sys.exit(f"{rel}: expected {expected} x {old[:70]!r}, found {n}")
        p.write_text(text.replace(old, new))


def copy_overlay(part: str):
    base = ROOT / "overlay" / part
    for f in sorted(base.rglob("*")):
        if f.is_file():
            dst = ROOT / part / f.relative_to(base)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dst)


# What must not remain in generated files. The `e2b_` API-key prefix is protocol, not branding.
FORBIDDEN = [
    (re.compile(r"\b(from|import) e2b\b(?!_)"), "e2b import"),
    (re.compile(r"from 'e2b'"), "e2b import"),
    (re.compile(r"\be2b_desktop\b|@e2b/desktop"), "upstream package name"),
    (re.compile(r"\bE2B_(API_KEY|DOMAIN|DEBUG|API_URL|SANDBOX_URL)\b"), "E2B_* variable"),
    (re.compile(r"e2b\.dev|e2b\.app"), "E2B domain"),
]

PIP_NAME = re.compile(r"\be2b-desktop\b")


def audit():
    problems = []
    paths = [*[ROOT / "template" / n for n in TEMPLATE_FILES], ROOT / "README.md",
             *[ROOT / "examples" / n / "README.md" for n in EXAMPLES]]
    for p in paths:
        for i, line in enumerate(p.read_text().splitlines(), 1):
            # noVNC's branch is also named e2b-desktop, so the pip name is checked in docs only
            checks = FORBIDDEN + ([(PIP_NAME, "upstream package name")] if p.suffix == ".md" else [])
            for rx, what in checks:
                if rx.search(line):
                    problems.append(f"{p.relative_to(ROOT)}:{i}: {what}: {line.strip()}")
    if problems:
        sys.exit("audit failed:\n  " + "\n  ".join(problems))


def pin(name: str) -> str:
    m = re.search(rf"^- {name} commit: `([0-9a-f]{{40}})`", (ROOT / "UPSTREAM.md").read_text(), re.M)
    if not m:
        sys.exit(f"UPSTREAM.md has no '- {name} commit: `<sha>`' line")
    return m.group(1)


def checkout(url: str, ref: str, given: Path | None, tmp: Path, name: str) -> Path:
    if given is None:
        given = tmp / name
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", url, str(given)], check=True)
        subprocess.run(["git", "-C", str(given), "checkout", "-q", ref], check=True)
    head = subprocess.run(["git", "-C", str(given), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    if head != ref:
        sys.exit(f"{given} is at {head}, UPSTREAM.md pins {ref}")
    return given


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--desktop", type=Path, help="e2b-dev/desktop checkout at the pinned commit")
    a = ap.parse_args()
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        desk = checkout(DESKTOP, pin("Desktop repo"), a.desktop, Path(tmp), "desktop")
        sync_template(desk)
        sync_readme(desk)
        sync_examples(desk)
        # The license is upstream's Apache-2.0 text, unchanged.
        up_lic = (desk / "LICENSE").read_text()
        if (ROOT / "LICENSE").read_text() != up_lic:
            sys.exit("LICENSE differs from upstream's Apache-2.0 text")
    audit()
    print("sync OK")


if __name__ == "__main__":
    main()
